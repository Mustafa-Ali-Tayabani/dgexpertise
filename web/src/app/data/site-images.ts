export function splitTitle(t: string) {
  const m = (t || "").trim().match(/^(.*?)[\s]*([!?.])?$/);
  const body = m ? m[1] : t || "", mark = m && m[2] ? m[2] : ".";
  const w = body.split(" ");
  const n = w.length > 4 ? 2 : 1;
  return { a: w.slice(0, -n).join(" "), b: w.slice(-n).join(" "), mark };
}
export function splitHead(t: string) {
  const w = (t || "").trim().split(" ");
  let n = 1; if (w.length > 1 && /^[!?:.]$/.test(w[w.length - 1])) n = 2;
  return { a: w.slice(0, -n).join(" "), b: w.slice(-n).join(" ") };
}
